export function computeSubtitleInlineStyles(preset: SubtitlePreset): {
  fontFamilyCss: string;
  textShadowCss: string;
  webkitTextStrokeCss: string;
  backgroundCss: string;
} {
  const fontFamilyMap: Record<SubtitlePreset['fontFamily'], string> = {
    sans: "'Be Vietnam Pro', 'Inter', -apple-system, BlinkMacSystemFont, 'Noto Sans KR', 'Noto Sans JP', 'Noto Sans SC', sans-serif",
    cjk: "'Noto Sans CJK SC', 'Pretendard', 'Hiragino Sans', 'PingFang SC', 'Be Vietnam Pro', sans-serif",
    rounded: "'Plus Jakarta Sans', 'Nunito', 'Be Vietnam Pro', system-ui, sans-serif",
    serif: "'Merriweather', 'Noto Serif', Georgia, serif",
    mono: "'JetBrains Mono', 'SFMono-Regular', Consolas, monospace",
  };

  const shadowMap: Record<SubtitlePreset['textShadow'], string> = {
    none: 'none',
    soft: '0 1px 4px rgba(0,0,0,0.65)',
    crisp: '0 2px 6px rgba(0,0,0,0.92), 0 0 2px rgba(0,0,0,0.95)',
    cinema: '0 2px 10px rgba(0,0,0,0.9), 0 1px 2px rgba(0,0,0,1)',
  };

  const outlineMap: Record<SubtitlePreset['textOutline'], string> = {
    none: '0px transparent',
    light: '0.5px rgba(0,0,0,0.75)',
    medium: '1px rgba(0,0,0,0.9)',
    strong: '1.6px rgba(0,0,0,0.98)',
  };

  const hex = preset.backgroundColor.replace('#', '');
  const r = parseInt(hex.slice(0, 2) || '00', 16);
  const g = parseInt(hex.slice(2, 4) || '00', 16);
  const b = parseInt(hex.slice(4, 6) || '00', 16);
  const alpha =
    preset.subtitleMode === 'minimal' ? 0 : Math.max(0, Math.min(1, preset.backgroundOpacity));

  return {
    fontFamilyCss: fontFamilyMap[preset.fontFamily] ?? fontFamilyMap.sans,
    textShadowCss: shadowMap[preset.textShadow] ?? shadowMap.soft,
    webkitTextStrokeCss: outlineMap[preset.textOutline] ?? outlineMap.none,
    backgroundCss: `rgba(${r}, ${g}, ${b}, ${alpha})`,
  };
}
