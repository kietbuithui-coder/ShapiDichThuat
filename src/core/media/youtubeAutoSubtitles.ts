interface PipedStreamsResponse {
  title?: string;
  uploader?: string;
  duration?: number;
  subtitles?: PipedSubtitleTrack[];
  audioStreams?: PipedAudioStream[];
}

interface LrcLibItem {
  id: number;
  trackName?: string;
  artistName?: string;
  duration?: number;
  syncedLyrics?: string | null;
  plainLyrics?: string | null;
}

