export interface YouTubeAutoSubtitleResult {
  title?: string;
  author?: string;
  sourceLabel: string; // e.g. 'Phụ đề gốc YouTube (Tiếng Hàn)', 'Phụ đề tự động YouTube', 'Lời thoại đồng bộ (LRCLIB)'
  detectedLanguage: ConcreteLanguageCode;
  cues: ParsedRawCue[];
  extractedAudioStreamUrl?: string;
}

interface YouTubeOEmbedResponse {
  title?: string;
  author_name?: string;
}

