function fetchWithTimeout(url: string, timeoutMs = 4500): Promise<Response> {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), timeoutMs);
  return fetch(url, { signal: ctrl.signal }).finally(() => clearTimeout(timer));
}

function hasCJKChars(text: string): boolean {
  return /[\uAC00-\uD7AF\u3040-\u30FF\u4E00-\u9FFF]/.test(text);
}

/**
 * Fetches official YouTube video title & channel name via CORS-enabled oEmbed
 */
export async function fetchYouTubeMetadata(
  videoId: string
): Promise<{ title: string; author: string } | null> {
  const ytUrl = `https://www.youtube.com/watch?v=${encodeURIComponent(videoId)}`;
  const endpoints = [
    `https://www.youtube.com/oembed?url=${encodeURIComponent(ytUrl)}&format=json`,
    `https://noembed.com/embed?url=${encodeURIComponent(ytUrl)}`,
  ];

  for (const ep of endpoints) {
    try {
      const res = await fetchWithTimeout(ep, 3500);
      if (!res.ok) continue;
      const data = (await res.json()) as YouTubeOEmbedResponse;
      if (data.title) {
        return {
          title: data.title.trim(),
          author: (data.author_name ?? '').trim(),
        };
      }
    } catch {
      // Try next metadata endpoint
    }
  }
  return null;
}

/**
 * Parses YouTube JSON3 (`fmt=json3`) timedtext events into clean sentence-level cues
 */
export function parseYouTubeJson3Captions(rawJson: string): ParsedRawCue[] {
  try {
    const parsed = JSON.parse(rawJson) as {
      events?: Array<{
        tStartMs?: number;
        dDurationMs?: number;
        segs?: Array<{ utf8?: string }>;
      }>;
    };
    if (!Array.isArray(parsed.events)) return [];

    const rawItems: Array<{ start: number; end: number; text: string }> = [];
    for (const ev of parsed.events) {
      if (typeof ev.tStartMs !== 'number' || !Array.isArray(ev.segs)) continue;
      const text = ev.segs
        .map((s) => s.utf8 ?? '')
        .join('')
        .replace(/\n+/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
      if (!text || /^\[.*\]$/.test(text) || /^♪+$/.test(text)) continue;
      const dur = typeof ev.dDurationMs === 'number' && ev.dDurationMs > 0 ? ev.dDurationMs : 2800;
      rawItems.push({
        start: ev.tStartMs,
        end: ev.tStartMs + dur,
        text,
      });
    }

    // Prevent overlapping auto-caption roll-up cues by clamping endTimestamp to next cue's startTimestamp
    const cues: ParsedRawCue[] = [];
    for (let i = 0; i < rawItems.length; i++) {
      const cur = rawItems[i];
      const next = rawItems[i + 1];
      const clampedEnd = next ? Math.min(cur.end, Math.max(cur.start + 450, next.start - 40)) : cur.end;
      // Deduplicate identical consecutive lines
      if (cues.length > 0 && cues[cues.length - 1].sourceText === cur.text) {
        cues[cues.length - 1].endTimestamp = clampedEnd;
        continue;
      }
      cues.push({
        id: `yt-j3-${i + 1}`,
        index: cues.length + 1,
        startTimestamp: cur.start,
        endTimestamp: clampedEnd,
        sourceText: cur.text,
      });
    }
    return cues;
  } catch {
    return [];
  }
}

/**
 * Parses YouTube XML (`timedtext` `<text start="1.23" dur="3.45">...</text>` or `<p t="1230" d="3450">`)
 */
export function parseYouTubeXmlCaptions(xmlText: string): ParsedRawCue[] {
  if (typeof DOMParser === 'undefined') return [];
  try {
    const doc = new DOMParser().parseFromString(xmlText, 'text/xml');
    const cues: ParsedRawCue[] = [];

    // Format 1: <text start="sec" dur="sec">
    const textNodes = Array.from(doc.getElementsByTagName('text'));
    if (textNodes.length > 0) {
      textNodes.forEach((node, idx) => {
        const startSec = parseFloat(node.getAttribute('start') ?? '0');
        const durSec = parseFloat(node.getAttribute('dur') ?? '2.8');
        const txt = (node.textContent ?? '').replace(/\s+/g, ' ').trim();
        if (!txt || /^♪+$/.test(txt)) return;
        const startMs = Math.round(startSec * 1000);
        const endMs = Math.round((startSec + (Number.isFinite(durSec) ? durSec : 2.8)) * 1000);
        cues.push({
          id: `yt-xml-${idx + 1}`,
          index: cues.length + 1,
          startTimestamp: startMs,
          endTimestamp: endMs,
          sourceText: txt,
        });
      });
    } else {
      // Format 2: TTML / SRV3 <p t="ms" d="ms"> or <p begin="00:00:01.200" end="00:00:04.000">
      const pNodes = Array.from(doc.getElementsByTagName('p'));
      pNodes.forEach((node, idx) => {
        const tAttr = node.getAttribute('t');
        const dAttr = node.getAttribute('d');
        const beginAttr = node.getAttribute('begin');
        const endAttr = node.getAttribute('end');
        let startMs = 0;
        let endMs = 0;

        if (tAttr !== null) {
          startMs = parseInt(tAttr, 10);
          endMs = startMs + (dAttr ? parseInt(dAttr, 10) : 2800);
        } else if (beginAttr) {
          startMs = parseTimecodeToMs(beginAttr);
          endMs = endAttr ? parseTimecodeToMs(endAttr) : startMs + 2800;
        }
        const txt = (node.textContent ?? '').replace(/\s+/g, ' ').trim();
        if (!txt || /^♪+$/.test(txt)) return;
        cues.push({
          id: `yt-ttml-${idx + 1}`,
          index: cues.length + 1,
          startTimestamp: startMs,
          endTimestamp: Math.max(startMs + 500, endMs),
          sourceText: txt,
        });
      });
    }

    // Clamp overlaps cleanly
    for (let i = 0; i < cues.length - 1; i++) {
      if (cues[i].endTimestamp > cues[i + 1].startTimestamp) {
        cues[i].endTimestamp = Math.max(
          cues[i].startTimestamp + 450,
          cues[i + 1].startTimestamp - 30
        );
      }
    }
    return cues;
  } catch {
    return [];
  }
}

function parseTimecodeToMs(tc: string): number {
  const m = tc.trim().match(/(?:(\d+):)?(\d{1,2}):(\d{2})[.,](\d{1,3})/);
  if (!m) return 0;
  const h = Number(m[1] ?? 0);
  const min = Number(m[2] ?? 0);
  const s = Number(m[3] ?? 0);
  const ms = Number((m[4] ?? '0').padEnd(3, '0').slice(0, 3));
  return ((h * 3600 + min * 60 + s) * 1000) + ms;
}

/**
 * Parses synchronized LRC lyrics (`[00:12.34] 사랑을 했다 우리가 만나`) into cues
 */
export function parseSyncedLrcToCues(lrcContent: string): ParsedRawCue[] {
  const lines = lrcContent.replace(/\r\n/g, '\n').split('\n');
  const raw: Array<{ startMs: number; text: string }> = [];

  for (const line of lines) {
    const timeMatches = [...line.matchAll(/\[(\d{1,2}):(\d{2})(?:[.:](\d{1,3}))?\]/g)];
    if (timeMatches.length === 0) continue;
    const lyricText = line.replace(/\[[^\]]+\]/g, '').trim();
    if (!lyricText || /^♪+$/.test(lyricText)) continue;

    for (const tm of timeMatches) {
      const min = parseInt(tm[1], 10);
      const sec = parseInt(tm[2], 10);
      const fracRaw = tm[3] ?? '0';
      const ms =
        fracRaw.length === 2
          ? parseInt(fracRaw, 10) * 10
          : parseInt(fracRaw.padEnd(3, '0').slice(0, 3), 10);
      raw.push({
        startMs: (min * 60 + sec) * 1000 + ms,
        text: lyricText,
      });
    }
  }

  raw.sort((a, b) => a.startMs - b.startMs);

  return raw.map((item, idx) => {
    const next = raw[idx + 1];
    const endMs = next
      ? Math.min(item.startMs + 7500, Math.max(item.startMs + 1200, next.startMs - 60))
      : item.startMs + 5000;
    return {
      id: `lrc-${idx + 1}`,
      index: idx + 1,
      startTimestamp: item.startMs,
      endTimestamp: endMs,
      sourceText: item.text,
    };
  });
}

function scoreTrackCode(codeRaw: string, autoGen: boolean, preferred: SourceLanguageCode): number {
  const code = codeRaw.toLowerCase();
  const penalty = autoGen ? 5 : 0;

  if (preferred === 'ko' && code.startsWith('ko')) return 100 - penalty;
  if (preferred === 'ja' && code.startsWith('ja')) return 100 - penalty;
  if (preferred === 'zh-CN' && (code === 'zh-cn' || code === 'zh-hans' || code === 'zh')) {
    return 100 - penalty;
  }
  if (preferred === 'zh-TW' && (code === 'zh-tw' || code === 'zh-hant' || code === 'zh-hk')) {
    return 100 - penalty;
  }

  if (code.startsWith('ko') || code.startsWith('ja') || code.startsWith('zh')) {
    return 85 - penalty;
  }
  if (code.startsWith('en')) return 45 - penalty;
  return 20 - penalty;
}

function parseAnyCaptionPayload(payload: string): ParsedRawCue[] {
  const trimmed = payload.trim();
  if (!trimmed) return [];
  if (trimmed.startsWith('{')) {
    const j3 = parseYouTubeJson3Captions(trimmed);
    if (j3.length > 0) return j3;
  }
  if (trimmed.startsWith('WEBVTT') || trimmed.includes('-->')) {
    try {
      const vtt = parseSubtitleFileContent(trimmed, 'captions.vtt');
      if (vtt.cues.length > 0) return vtt.cues;
    } catch {
      // Fall through
    }
  }
  if (trimmed.startsWith('<')) {
    const xml = parseYouTubeXmlCaptions(trimmed);
    if (xml.length > 0) return xml;
  }
  return [];
}

async function tryFetchFromPiped(
  videoId: string,
  preferredLang: SourceLanguageCode
): Promise<YouTubeAutoSubtitleResult | null> {
  const attempts = PIPED_API_BASES.map(async (base) => {
    const res = await fetchWithTimeout(`${base}/streams/${encodeURIComponent(videoId)}`, 4800);
    if (!res.ok) throw new Error('Piped non-200');
    const data = (await res.json()) as PipedStreamsResponse;
    if (!data || (!data.subtitles?.length && !data.audioStreams?.length)) {
      throw new Error('Empty Piped payload');
    }
    return data;
  });

  let streamData: PipedStreamsResponse | null = null;
  try {
    streamData = await Promise.any(attempts);
  } catch {
    return null;
  }

  const bestAudio = streamData.audioStreams
    ?.filter((a) => a.url)
    .sort((a, b) => (b.bitrate ?? 0) - (a.bitrate ?? 0))[0]?.url;

  const subs = [...(streamData.subtitles ?? [])].filter((s) => s.url);
  subs.sort(
    (a, b) =>
      scoreTrackCode(b.code ?? '', Boolean(b.autoGenerated), preferredLang) -
      scoreTrackCode(a.code ?? '', Boolean(a.autoGenerated), preferredLang)
  );

  for (const track of subs.slice(0, 3)) {
    try {
      const capRes = await fetchWithTimeout(track.url, 4500);
      if (!capRes.ok) continue;
      const body = await capRes.text();
      const cues = parseAnyCaptionPayload(body);
      if (cues.length > 0) {
        const sampleTxt = cues
          .slice(0, 8)
          .map((c) => c.sourceText)
          .join(' ');
        const detected = detectCJKLanguage(
          sampleTxt,
          preferredLang === 'auto' ? 'ko' : preferredLang
        ).language;
        return {
          title: streamData.title,
          author: streamData.uploader,
          sourceLabel: track.autoGenerated
            ? `Phụ đề nhận diện giọng nói YouTube (${track.code ?? detected})`
            : `Phụ đề gốc YouTube (${track.code ?? detected})`,
          detectedLanguage: detected,
          cues,
          extractedAudioStreamUrl: bestAudio,
        };
      }
    } catch {
      // Try next track
    }
  }

  if (bestAudio) {
    return {
      title: streamData.title,
      author: streamData.uploader,
      sourceLabel: 'Luồng âm thanh YouTube',
      detectedLanguage: preferredLang === 'auto' ? 'ko' : preferredLang,
      cues: [],
      extractedAudioStreamUrl: bestAudio,
    };
  }

  return null;
}

async function tryFetchFromInvidious(
  videoId: string,
  preferredLang: SourceLanguageCode
): Promise<YouTubeAutoSubtitleResult | null> {
  for (const base of INVIDIOUS_API_BASES) {
    try {
      const res = await fetchWithTimeout(
        `${base}/api/v1/captions/${encodeURIComponent(videoId)}`,
        4000
      );
      if (!res.ok) continue;
      const data = (await res.json()) as {
        captions?: Array<{ label?: string; language_code?: string; url?: string }>;
      };
      if (!Array.isArray(data.captions) || data.captions.length === 0) continue;

      const sorted = [...data.captions].sort((a, b) => {
        const autoA = /auto/i.test(a.label ?? '');
        const autoB = /auto/i.test(b.label ?? '');
        return (
          scoreTrackCode(b.language_code ?? '', autoB, preferredLang) -
          scoreTrackCode(a.language_code ?? '', autoA, preferredLang)
        );
      });

      const pick = sorted[0];
      if (!pick?.url) continue;
      const fullUrl = pick.url.startsWith('http') ? pick.url : `${base}${pick.url}`;
      const vttRes = await fetchWithTimeout(fullUrl, 4200);
      if (!vttRes.ok) continue;
      const vttText = await vttRes.text();
      const cues = parseAnyCaptionPayload(vttText);
      if (cues.length > 0) {
        const sampleTxt = cues
          .slice(0, 8)
          .map((c) => c.sourceText)
          .join(' ');
        const detected = detectCJKLanguage(
          sampleTxt,
          preferredLang === 'auto' ? 'ko' : preferredLang
        ).language;
        return {
          sourceLabel: `Phụ đề YouTube (${pick.language_code ?? detected})`,
          detectedLanguage: detected,
          cues,
        };
      }
    } catch {
      // Try next Invidious instance
    }
  }
  return null;
}

/**
 * Builds smart search queries from noisy YouTube MV titles like:
 * "iKON - ‘사랑을 했다(LOVE SCENARIO)’ M/V" -> ["iKON 사랑을 했다", "iKON LOVE SCENARIO", "사랑을 했다"]
 */
export function buildSongSearchQueries(title: string, author: string): string[] {
  const queries: string[] = [];
  const cleanAuthor = author
    .replace(/\b(official|entertainment|music|labels|vevo|channel|tv)\b/gi, '')
    .replace(/\s+/g, ' ')
    .trim();

  // Extract quoted title if present: ‘사랑을 했다(LOVE SCENARIO)’ or 'LOVE SCENARIO' or 「アイドル」
  const quoteMatch = title.match(/[‘'“"「『]([^’'”"」』]{2,60})[’'”"」』]/);
  if (quoteMatch) {
    const inside = quoteMatch[1].trim();
    const parenMatch = inside.match(/^([^(（]+)[(（]([^)）]+)[)）]/);
    if (parenMatch) {
      const part1 = parenMatch[1].trim();
      const part2 = parenMatch[2].trim();
      if (cleanAuthor) queries.push(`${cleanAuthor} ${part1}`);
      if (cleanAuthor) queries.push(`${cleanAuthor} ${part2}`);
      queries.push(part1);
    } else {
      if (cleanAuthor) queries.push(`${cleanAuthor} ${inside}`);
      queries.push(inside);
    }
  }

  // Also strip MV / Official Video / Lyrics brackets
  const stripped = title
    .replace(/\[[^\]]*\]/g, ' ')
    .replace(/\((?:official|m\/v|mv|music video|lyric|audio|live|hd|4k)[^)]*\)/gi, ' ')
    .replace(/\b(m\/v|mv|official\s*video|music\s*video|official\s*audio|lyrics?)\b/gi, ' ')
    .replace(/[‘’“”"'「」『』｜|]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

  if (stripped.length >= 2 && !queries.includes(stripped)) {
    queries.push(stripped);
  }

  return queries.slice(0, 4);
}

/**
 * Searches LRCLIB (CORS-enabled public synced lyrics database) for exact `[mm:ss.xx]` CJK lines
 */
async function tryFetchSyncedLyricsFromLrcLib(
  title: string,
  author: string,
  preferredLang: SourceLanguageCode,
  videoDurationSec?: number
): Promise<YouTubeAutoSubtitleResult | null> {
  const queries = buildSongSearchQueries(title, author);
  for (const q of queries) {
    try {
      const res = await fetchWithTimeout(
        `https://lrclib.net/api/search?q=${encodeURIComponent(q)}`,
        4200
      );
      if (!res.ok) continue;
      const items = (await res.json()) as LrcLibItem[];
      if (!Array.isArray(items) || items.length === 0) continue;

      const withSynced = items.filter((it) => it.syncedLyrics && it.syncedLyrics.trim().length > 20);
      if (withSynced.length === 0) continue;

      // Prefer entries with CJK characters and closest duration to the video
      withSynced.sort((a, b) => {
        const aCjk = hasCJKChars(a.syncedLyrics ?? '') ? 100 : 0;
        const bCjk = hasCJKChars(b.syncedLyrics ?? '') ? 100 : 0;
        const aDurDiff =
          videoDurationSec && a.duration ? Math.abs(videoDurationSec - a.duration) : 0;
        const bDurDiff =
          videoDurationSec && b.duration ? Math.abs(videoDurationSec - b.duration) : 0;
        return bCjk - aDurDiff - (aCjk - bDurDiff);
      });

      const best = withSynced[0];
      if (!best?.syncedLyrics) continue;
      const cues = parseSyncedLrcToCues(best.syncedLyrics);
      if (cues.length >= 3) {
        const sampleTxt = cues
          .slice(0, 8)
          .map((c) => c.sourceText)
          .join(' ');
        const detected = detectCJKLanguage(
          sampleTxt,
          preferredLang === 'auto' ? 'ko' : preferredLang
        ).language;
        return {
          title,
          author,
          sourceLabel: `Lời thoại đồng bộ thời gian thực (${best.trackName ?? q})`,
          detectedLanguage: detected,
          cues,
        };
      }
    } catch {
      // Try next query
    }
  }
  return null;
}

/**
 * Master Automatic Subtitle Extractor for YouTube Videos:
 * Runs automatically as soon as any YouTube link is loaded — zero clicks or screen-share popups!
 */
export async function resolveAutomaticYouTubeSubtitles(
  videoId: string,
  preferredLang: SourceLanguageCode,
  videoDurationSec?: number
): Promise<YouTubeAutoSubtitleResult | null> {
  const metaPromise = fetchYouTubeMetadata(videoId);

  // Race YouTube Caption Gateways first
  const [meta, pipedResult] = await Promise.all([
    metaPromise,
    tryFetchFromPiped(videoId, preferredLang),
  ]);

  const knownTitle = pipedResult?.title || meta?.title || '';
  const knownAuthor = pipedResult?.author || meta?.author || '';
  const looksLikeMusicVideo =
    /\b(m\/v|mv|music\s*video|official\s*video|official\s*audio|lyric|歌ってみた|mv公開)\b/i.test(
      knownTitle
    );

  // If Piped returned CJK captions, use them immediately!
  if (pipedResult && pipedResult.cues.length > 0) {
    const hasCjkInPiped = hasCJKChars(
      pipedResult.cues
        .slice(0, 6)
        .map((c) => c.sourceText)
        .join(' ')
    );
    if (hasCjkInPiped || !looksLikeMusicVideo) {
      return {
        ...pipedResult,
        title: knownTitle || pipedResult.title,
        author: knownAuthor || pipedResult.author,
      };
    }
  }

  // Try Invidious captions + LRCLIB synced lyrics in parallel!
  const [invRes, lrcRes] = await Promise.all([
    tryFetchFromInvidious(videoId, preferredLang),
    knownTitle
      ? tryFetchSyncedLyricsFromLrcLib(knownTitle, knownAuthor, preferredLang, videoDurationSec)
      : Promise.resolve(null),
  ]);

  // For Music Videos, if LRCLIB found genuine CJK synced lines, prefer CJK synced lines so user gets Original Korean/Japanese/Chinese + Vietnamese!
  if (lrcRes && lrcRes.cues.length > 0 && looksLikeMusicVideo) {
    return {
      ...lrcRes,
      extractedAudioStreamUrl: pipedResult?.extractedAudioStreamUrl,
    };
  }

  if (invRes && invRes.cues.length > 0) {
    return {
      ...invRes,
      title: knownTitle || invRes.title,
      author: knownAuthor || invRes.author,
      extractedAudioStreamUrl: pipedResult?.extractedAudioStreamUrl,
    };
  }

  if (lrcRes && lrcRes.cues.length > 0) {
    return {
      ...lrcRes,
      extractedAudioStreamUrl: pipedResult?.extractedAudioStreamUrl,
    };
  }

  if (pipedResult) {
    return {
      ...pipedResult,
      title: knownTitle || pipedResult.title,
      author: knownAuthor || pipedResult.author,
    };
  }

  if (knownTitle) {
    return {
      title: knownTitle,
      author: knownAuthor,
      sourceLabel: 'YouTube Video',
      detectedLanguage: preferredLang === 'auto' ? 'ko' : preferredLang,
      cues: [],
    };
  }

  return null;
}
